"""Files compose mounts that depend on settings: the gateway configuration with one passthrough listener per
allowed address, the matching network aliases, and ``build-info.json``."""

from __future__ import annotations

import json
from pathlib import Path
from typing import cast

ALLOWLIST_MARKER = "# @ALLOWLIST@\n"


def parse_allow_lines(text: str) -> list[tuple[str, int]]:
    """The "host port" lines ``parse_allowlist`` prints."""
    entries: list[tuple[str, int]] = []
    for line in text.splitlines():
        if line.strip():
            host, port = line.split()
            entries.append((host, int(port)))
    return entries


def render_gateway(template: str, entries: list[tuple[str, int]]) -> str:
    blocks = [
        f"frontend allow_{index}\n    mode tcp\n    bind :{port}\n    default_backend allow_{index}_server\n\n"
        f"backend allow_{index}_server\n    mode tcp\n"
        f"    server upstream {host}:{port} resolvers docker init-addr libc,none\n"
        for index, (host, port) in enumerate(entries, start=1)
    ]
    return template.replace(ALLOWLIST_MARKER, "\n".join(blocks))


def render_allow_override(entries: list[tuple[str, int]]) -> str:
    aliases = ", ".join(host for host, _ in entries)
    return (
        "# Generated by tools/work.sh from SIDEKICK_WORK_ALLOW: the allowed names resolve to the gateway.\n"
        f"services:\n  gateway:\n    networks:\n      edge:\n        aliases: [{aliases}]\n"
    )


def write_gateway_files(template_path: Path, out_dir: Path, entries: list[tuple[str, int]]) -> None:
    """gateway.haproxy.cfg always; allow.compose.yaml only with entries (an old one is removed otherwise)."""
    template = template_path.read_text(encoding="utf-8")
    (out_dir / "gateway.haproxy.cfg").write_text(render_gateway(template, entries), encoding="utf-8")
    override = out_dir / "allow.compose.yaml"
    if entries:
        override.write_text(render_allow_override(entries), encoding="utf-8")
    elif override.exists():
        override.unlink()


def build_info(
    old: dict[str, str], commit: str, commit_date: str, now: str, previous: str, updated: bool
) -> dict[str, str]:
    """Which commit this checkout is on, when the image was built and when it was last updated."""
    return {
        "commit": commit,
        "commit_date": commit_date,
        "built_at": now,
        "updated_at": now if updated else old.get("updated_at", now),
        "previous_commit": previous or old.get("previous_commit", ""),
    }


def write_build_info(path: Path, commit: str, commit_date: str, now: str, previous: str, updated: bool) -> None:
    old: dict[str, str] = {}
    if path.exists():
        try:
            loaded = json.loads(path.read_text(encoding="utf-8"))
            old = cast("dict[str, str]", loaded) if isinstance(loaded, dict) else {}
        except ValueError:
            old = {}
    info = build_info(old, commit, commit_date, now, previous, updated)
    path.write_text(json.dumps(info, indent=2) + "\n", encoding="utf-8")
