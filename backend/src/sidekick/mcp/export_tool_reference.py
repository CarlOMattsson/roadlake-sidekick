"""Render the readable MCP tool reference (`docs/reference/mcp/`) from the generated contract.

The input is `contracts/mcp-tools.generated.json`, the curated tool surface that
`sidekick.mcp.export_contract` exports. The output is deterministic Markdown, one page per area plus
an index and a page for the app-only tools (the ones the MCP App rooms call and the model never
sees). Each tool has a one-line description, its access kind, its scopes, a parameter table with
nested fields and a short summary of the structured answer.

The contract carries no scope information and must not change, so the scopes come from
`sidekick.mcp.tool_scopes` (built from the tables the server enforces, `reply_scopes` among them).
`AREAS` below only groups the tools into pages; a tool that is in the contract but in no area (or in
no scope entry), or the reverse, is an error, so a new tool cannot ship without a place in the
reference.

Regenerate or verify with:
    uv run --project backend python -m sidekick.mcp.export_tool_reference
    uv run --project backend python -m sidekick.mcp.export_tool_reference --check
"""

