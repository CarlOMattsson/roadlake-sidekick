_SENTENCE_END = re.compile(r"(?<=[.!?])\s+(?=[A-Z])")
_RECORD_NAME = re.compile(r"[A-Z][A-Za-z0-9]*[a-z][A-Za-z0-9]*")
_NESTING_HINT = (
    "A nested field is listed under its parent as `parent.field`; `parent[].field` is a field of "
    "each item in the list. Required means required inside its parent."
)
_FORMAT_NOTES = {"date-time": "ISO 8601 date and time", "date": "ISO 8601 date"}


def _escape(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


def _first_sentence(text: str) -> str:
    return _SENTENCE_END.split(" ".join(text.split()), maxsplit=1)[0]


def _summary(description: str) -> str:
    """The first sentence of a tool description, on one line."""
    return _escape(_first_sentence(description))


def _alternatives(schema: dict[str, Any]) -> list[dict[str, Any]]:
    return schema.get("anyOf") or schema.get("oneOf") or [schema]


def _variants(schema: dict[str, Any]) -> list[dict[str, Any]]:
    """The non-null alternatives of a schema (the schema itself when it has no `anyOf`)."""
    return [option for option in _alternatives(schema) if option.get("type") != "null"]


def _nullable(schema: dict[str, Any]) -> bool:
    return any(option.get("type") == "null" for option in _alternatives(schema))


def _record_name(schema: dict[str, Any]) -> str:
    """The model class name pydantic puts in an object's `title`, else the plain word `object`."""
    title = schema.get("title")
    return title if isinstance(title, str) and _RECORD_NAME.fullmatch(title) else "object"


def _type(schema: dict[str, Any], *, named: bool = False) -> str:
    """The type of a schema; with `named`, an object is shown by its model class name."""
    names: list[str] = []
    for variant in _variants(schema):
        if "const" in variant:
            name = json.dumps(variant["const"])
        elif variant.get("type") == "array":
            name = (
                f"array of {_type(variant['items'], named=named)}"
                if "items" in variant
                else "array"
            )
        elif variant.get("type") == "object" and named:
            name = _record_name(variant)
        elif variant.get("format"):
            name = str(variant["format"])
        else:
            name = str(variant.get("type", "any"))
        if name not in names:
            names.append(name)
    return " or ".join(names) or "any"


def _range(low: Any, high: Any, unit: str) -> str | None:
    if low is not None and high is not None:
        return f"{low} to {high} {unit}"
    if high is not None:
        return f"up to {high} {unit}"
    if low is not None:
        return f"at least {low} {unit}"
    return None


def _notes(schema: dict[str, Any]) -> str:
    notes: list[str] = []
    default = schema.get("default")
    if default is not None:
        notes.append(f"default `{json.dumps(default)}`")
    for variant in _variants(schema):
        if "enum" in variant:
            notes.append("one of " + ", ".join(f"`{value}`" for value in variant["enum"]))
        for low, high, unit in (
            (variant.get("minLength"), variant.get("maxLength"), "characters"),
            (variant.get("minItems"), variant.get("maxItems"), "items"),
        ):
            if text := _range(low, high, unit):
                notes.append(text)
        if variant.get("exclusiveMinimum") is not None:
            notes.append(f"above {variant['exclusiveMinimum']}")
        if text := _range(variant.get("minimum"), variant.get("maximum"), ""):
            notes.append(text.strip())
        if variant.get("uniqueItems"):
            notes.append("unique")
        if "pattern" in variant:
            notes.append(f"pattern `{variant['pattern']}`")
        if variant.get("format") in _FORMAT_NOTES:
            notes.append(_FORMAT_NOTES[variant["format"]])
        if "enum" in (items := _object(variant.get("items"))):
            notes.append("items: " + ", ".join(f"`{value}`" for value in items["enum"]))
    if _nullable(schema):
        notes.append("may be null")
    if schema.get("description"):
        notes.append(_first_sentence(str(schema["description"])))
    return _escape("; ".join(dict.fromkeys(notes))) or "-"


@dataclass(frozen=True, slots=True)
class _Row:
    path: str
    type: str
    required: bool
    notes: str


def _object_variants(schema: dict[str, Any]) -> list[tuple[str, dict[str, Any]]]:
    """The nested objects of a parameter: the object itself, or the objects its array holds.

    Each comes with the path suffix of its fields (`.` for an object, `[].` for an array item). When
    an array holds several object shapes, a suffix names the shape by its `type` constant.
    """
    found: list[tuple[str, dict[str, Any]]] = []
    for variant in _variants(schema):
        if variant.get("type") == "object" and variant.get("properties"):
            found.append((".", variant))
        elif variant.get("type") == "array" and isinstance(variant.get("items"), dict):
            shapes = [item for item in _variants(variant["items"]) if item.get("properties")]
            for index, item in enumerate(shapes, start=1):
                label = ""
                if len(shapes) > 1:
                    const = _object(_object(item["properties"].get("type"))).get("const")
                    label = f"type={const}" if const else f"variant {index}"
                found.append((f"[{label}].", item))
    return found


def _rows(
    properties: dict[str, Any], required: set[str], prefix: str = "", depth: int = 0
) -> list[_Row]:
    rows: list[_Row] = []
    for name in sorted(properties, key=lambda key: (key not in required, key)):
        schema = properties[name]
        rows.append(_Row(f"{prefix}{name}", _type(schema), name in required, _notes(schema)))
        if depth + 1 >= MAX_NESTING:
            continue
        for suffix, child in _object_variants(schema):
            rows += _rows(
                child["properties"],
                set(child.get("required", [])),
                f"{prefix}{name}{suffix}",
                depth + 1,
            )
    return rows


def _parameters(tool: dict[str, Any]) -> list[str]:
    properties: dict[str, Any] = tool["inputSchema"].get("properties", {})
    if not properties:
        return ["No parameters.", ""]
    required = set(tool["inputSchema"].get("required", []))
    lines = [
        "| Parameter | Type | Required | Notes |",
        "| --- | --- | --- | --- |",
    ]
    lines += [
        f"| `{row.path}` | {_escape(row.type)} | {'yes' if row.required else 'no'} | {row.notes} |"
        for row in _rows(properties, required)
    ]
    lines.append("")
    if any(_object_variants(_object(schema)) for schema in properties.values()):
        lines += [_NESTING_HINT, ""]
    return lines


def _output(tool: dict[str, Any]) -> str:
    """A one-line summary of the structured answer, from the tool's output schema."""
    schema = _object(tool.get("outputSchema"))
    properties: dict[str, Any] = schema.get("properties", {})
    if not properties:
        return "No structured fields."
    required = set(schema.get("required", []))
    names = sorted(properties, key=lambda key: (key not in required, key))
    fields = [
        f"`{name}` ({_type(properties[name], named=True)}"
        f"{' or null' if _nullable(properties[name]) else ''})"
        for name in names[:MAX_OUTPUT_FIELDS]
    ]
    more = f" and {len(names) - MAX_OUTPUT_FIELDS} more" if len(names) > MAX_OUTPUT_FIELDS else ""
    title = _record_name(schema)
    head = f"`{title}` with " if title != "object" else ""
    return f"{head}{', '.join(fields)}{more}."


def _object(value: Any) -> dict[str, Any]:
    return cast("dict[str, Any]", value) if isinstance(value, dict) else {}


def _access(tool: dict[str, Any]) -> str:
    annotations = _object(tool.get("annotations"))
    if annotations.get("readOnlyHint"):
        return "read"
    return "write (destructive)" if annotations.get("destructiveHint") else "write"


def _is_app_only(tool: dict[str, Any]) -> bool:
    return _object(_object(tool.get("_meta")).get("ui")).get("visibility") == ["app"]


def _tool_section(tool: dict[str, Any], level: str) -> list[str]:
    name = tool["name"]
    return [
        f"{level} `{name}`",
        "",
        _summary(tool["description"]),
        "",
        f"Access: {_access(tool)}",
        "",
        f"Scopes: {describe(TOOL_SCOPES[name])}.",
        "",
        f"Returns: {_output(tool)}",
        "",
        *_parameters(tool),
    ]


def _check_coverage(by_name: dict[str, dict[str, Any]]) -> None:
    placed = [name for area in AREAS for name in area.tools]
    if len(placed) != len(set(placed)):
        raise ValueError("a tool is listed in more than one area")
    if missing := sorted(set(by_name) - set(placed)):
        raise ValueError(f"tools in the contract but in no area of AREAS: {', '.join(missing)}")
    if unknown := sorted(set(placed) - set(by_name)):
        raise ValueError(f"AREAS names tools that are not in the contract: {', '.join(unknown)}")
    if unscoped := sorted(set(by_name) - set(TOOL_SCOPES)):
        raise ValueError(f"tools in the contract but not in TOOL_SCOPES: {', '.join(unscoped)}")
    if stale := sorted(set(TOOL_SCOPES) - set(by_name)):
        raise ValueError(
            f"TOOL_SCOPES names tools that are not in the contract: {', '.join(stale)}"
        )


def _header(title: str, description: str | None = None) -> list[str]:
    summary = [f"<!-- description: {description} -->", ""] if description else []
    return [
        f"# {title}",
        "",
        *summary,
        f"{GENERATED_MARKER} from `contracts/mcp-tools.generated.json`. Do not edit by hand. -->",
        "",
    ]


def _area_page(area: Area, tools: list[dict[str, Any]]) -> str:
    lines = [
        *_header(f"MCP tools: {area.title}"),
        f"[MCP tool reference](index.md) | {len(tools)} model-visible "
        f"{'tool' if len(tools) == 1 else 'tools'}. The tools of this area that only the MCP App "
        "rooms call are on the [app-only page](app-only.md).",
        "",
    ]
    for tool in tools:
        lines += _tool_section(tool, "##")
    return "\n".join(lines).rstrip("\n") + "\n"


def _app_only_page(groups: list[tuple[Area, list[dict[str, Any]]]]) -> str:
    total = sum(len(tools) for _, tools in groups)
    lines = [
        *_header(
            "MCP tools: app-only",
            "The MCP tools that only the MCP App rooms call to show and edit records. "
            "Claude cannot see or call them, and they check the same scopes as every other tool.",
        ),
        f"[MCP tool reference](index.md) | {total} tools.",
        "",
        'These tools are declared with `visibility: ["app"]`. The MCP App rooms call them to '
        "show and edit records; the model never sees them, so Claude cannot call them. They check "
        "the same scopes as every other tool.",
        "",
    ]
    for area, tools in groups:
        lines += [f"## {area.title}", ""]
        for tool in tools:
            lines += _tool_section(tool, "###")
    return "\n".join(lines).rstrip("\n") + "\n"


def _index_page(
    tools: list[dict[str, Any]],
    model_groups: list[tuple[Area, list[dict[str, Any]]]],
    app_groups: list[tuple[Area, list[dict[str, Any]]]],
) -> str:
    app_total = sum(len(group) for _, group in app_groups)
    lines = [
        *_header("MCP tool reference"),
        f"Sidekick exposes {len(tools)} MCP tools: {len(tools) - app_total} that Claude can call "
        f"and {app_total} that only the MCP App rooms call. The executable truth is the generated "
        "contract, [contracts/mcp-tools.generated.json](../../../contracts/"
        "mcp-tools.generated.json); these pages are rendered from it and a test fails when the "
        "two differ.",
        "",
        "- **Access** is `read` for tools that change nothing and `write` for tools that create or "
        "change records; `write (destructive)` marks writes that remove or overwrite data.",
        "- **Scopes** are what the server enforces. They come from the code, not from this text: "
        "the scope of each use case, plus the read scope the reply of a write tool needs "
        "(`sidekick.mcp.reply_scopes`). A tool that works per kind of record answers with the "
        "kinds the session can read.",
        "- **Returns** names the top-level fields of the structured answer.",
        "- Almost every write takes an `idempotency_key` (a retry does not repeat the change) or "
        "an expected `version` (a stale write is refused).",
        "- Parameters marked `required` must be present; every other parameter can be left out.",
        "",
        "## Model-visible tools",
        "",
    ]
    for area, group in model_groups:
        lines += [f"### [{area.title}]({area.page})", ""]
        lines += [
            f"- [`{tool['name']}`]({area.page}#{tool['name']}): {_summary(tool['description'])} "
            f"({_access(tool)})"
            for tool in group
        ]
        lines.append("")
    lines += [
        "## App-only tools",
        "",
        f"The [{app_total} app-only tools](app-only.md) are called by the MCP App rooms and are "
        "hidden from the model:",
        "",
    ]
    for area, group in app_groups:
        lines += [
            f"- {area.title}: "
            + ", ".join(f"[`{tool['name']}`]({APP_ONLY_PAGE}#{tool['name']})" for tool in group)
        ]
    return "\n".join(lines).rstrip("\n") + "\n"


def render_pages(tools: list[dict[str, Any]]) -> dict[str, str]:
    """Every page of the reference, keyed by file name."""
    by_name = {tool["name"]: tool for tool in tools}
    _check_coverage(by_name)
    model_groups: list[tuple[Area, list[dict[str, Any]]]] = []
    app_groups: list[tuple[Area, list[dict[str, Any]]]] = []
    for area in AREAS:
        members = [by_name[name] for name in area.tools]
        if model := [tool for tool in members if not _is_app_only(tool)]:
            model_groups.append((area, model))
        if app := [tool for tool in members if _is_app_only(tool)]:
            app_groups.append((area, app))
    pages = {area.page: _area_page(area, group) for area, group in model_groups}
    pages[APP_ONLY_PAGE] = _app_only_page(app_groups)
    pages[INDEX_PAGE] = _index_page(tools, model_groups, app_groups)
    return pages


def stale_problems(pages: dict[str, str], directory: Path) -> list[str]:
    """What differs between the rendered pages and the directory; empty when it is up to date."""
    problems: list[str] = []
    for name, rendered in sorted(pages.items()):
        path = directory / name
        if not path.is_file():
            problems.append(f"missing: {path}")
        elif path.read_text(encoding="utf-8") != rendered:
            problems.append(f"out of date: {path}")
    for path in sorted(directory.glob("*.md")) if directory.is_dir() else []:
        if path.name not in pages and GENERATED_MARKER in path.read_text(encoding="utf-8"):
            problems.append(f"no longer generated: {path}")
    return problems


def write_pages(pages: dict[str, str], directory: Path) -> None:
    directory.mkdir(parents=True, exist_ok=True)
    for name, rendered in pages.items():
        (directory / name).write_text(rendered, encoding="utf-8")
    for path in directory.glob("*.md"):
        if path.name not in pages and GENERATED_MARKER in path.read_text(encoding="utf-8"):
            path.unlink()


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--contract", type=Path, default=DEFAULT_CONTRACT)
    parser.add_argument("--output-dir", type=Path, default=DEFAULT_OUTPUT_DIR)
    parser.add_argument(
        "--check",
        action="store_true",
        help="write nothing; exit 1 when --output-dir differs from what the contract renders",
    )
    args = parser.parse_args()
    pages = render_pages(json.loads(args.contract.read_text(encoding="utf-8")))
    if not args.check:
        write_pages(pages, args.output_dir)
        return 0
    problems = stale_problems(pages, args.output_dir)
    for problem in problems:
        print(problem, file=sys.stderr)
    if problems:
        print(
            "regenerate with: "
            "uv run --project backend python -m sidekick.mcp.export_tool_reference",
            file=sys.stderr,
        )
    return 1 if problems else 0


if __name__ == "__main__":
    raise SystemExit(main())
