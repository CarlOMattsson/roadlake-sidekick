"""Render the configuration reference (`docs/reference/configuration.md`) from `Settings`.

The class `sidekick.shared.config.Settings` is the one list of environment variables the backend
reads. Each field carries a `Field(description=...)`; this module turns the fields into one
deterministic Markdown page: name, type with limits, default, whether the value is secret, and the
description. Nothing here reads the environment, so the output never holds a configured value.

`GROUPS` only orders the fields into sections. A field that matches no group is an error, so a new
setting cannot ship without a place in the reference (or without a description).

Regenerate or verify with:
    uv run --project backend python -m sidekick.shared.export_settings_reference
    uv run --project backend python -m sidekick.shared.export_settings_reference --check
"""

import argparse
import sys
import types
from dataclasses import dataclass
from datetime import time
from pathlib import Path
from typing import Any, Literal, Union, get_args, get_origin

from pydantic import SecretStr
from pydantic.fields import FieldInfo

from sidekick.shared.config import PLACEHOLDER_PREFIXES, Settings

DEFAULT_OUTPUT = Path("docs/reference/configuration.md")
GENERATED_MARKER = "<!-- Generated by `sidekick.shared.export_settings_reference`"


@dataclass(frozen=True, slots=True)
class Group:
    title: str
    summary: str
    prefixes: tuple[str, ...] = ()
    names: tuple[str, ...] = ()

    def matches(self, name: str) -> bool:
        return name in self.names or name.startswith(self.prefixes)


GROUPS: tuple[Group, ...] = (
    Group(
        "Core",
        "Mode, database and the secrets every instance needs.",
        names=(
            "environment",
            "database_url",
            "cursor_signing_secret",
            "token_pepper",
        ),
    ),
    Group(
        "Database time budgets",
        "Limits on every application database connection. Migrations use their own connection.",
        prefixes=("db_",),
    ),
    Group("Backups", "Scheduled encrypted database backups.", prefixes=("backup_",)),
    Group(
        "Derived memory",
        "Memory derived from records and sent to Hindsight.",
        prefixes=("memory_",),
    ),
    Group(
        "MCP server and sign-in",
        "The public MCP server, its name, language and authentication.",
        prefixes=("mcp_",),
    ),
    Group(
        "Companion app and push",
        "The Android companion adapter and durable push delivery.",
        prefixes=("companion_", "push_"),
    ),
    Group(
        "Request limits",
        "Protection of the public surface against slow and failing clients.",
        prefixes=("body_read_", "oauth_body_", "max_buffered_", "failed_auth_"),
    ),
    Group(
        "Instance",
        "Time zone, rooms, update reminder and build information.",
        names=("owner_timezone", "enabled_rooms", "update_reminder_days"),
        prefixes=("build_",),
    ),
    Group(
        "License", "The key that verifies the instance's licence.", names=("license_public_key",)
    ),
)

_SCALARS: dict[Any, str] = {
    str: "string",
    int: "integer",
    float: "number",
    bool: "boolean",
    Path: "path",
    time: "time of day (HH:MM)",
    SecretStr: "secret string",
}


def _union_members(annotation: Any) -> tuple[Any, ...] | None:
    if get_origin(annotation) in (Union, types.UnionType):
        return get_args(annotation)
    return None


def _is_secret_str(annotation: Any) -> bool:
    members = _union_members(annotation)
    return SecretStr in members if members else annotation is SecretStr


def _type_text(annotation: Any) -> str:
    members = _union_members(annotation)
    if members is not None:
        present = [member for member in members if member is not type(None)]
        text = " or ".join(_type_text(member) for member in present)
        return f"{text}, optional" if len(present) != len(members) else text
    if get_origin(annotation) is Literal:
        return "one of " + ", ".join(f"`{value}`" for value in get_args(annotation))
    return _SCALARS[annotation]


def _limits(field: FieldInfo) -> str:
    bounds: dict[str, Any] = {}
    for item in field.metadata:
        for key in ("ge", "gt", "le", "lt", "min_length"):
            if (value := getattr(item, key, None)) is not None:
                bounds[key] = value

    def number(value: Any) -> str:
        return f"{value:,}" if isinstance(value, int) else str(value)

    parts: list[str] = []
    if "ge" in bounds:
        parts.append(f"min {number(bounds['ge'])}")
    if "gt" in bounds:
        parts.append(f"above {number(bounds['gt'])}")
    if "le" in bounds:
        parts.append(f"max {number(bounds['le'])}")
    if "lt" in bounds:
        parts.append(f"below {number(bounds['lt'])}")
    if "min_length" in bounds:
        parts.append(f"at least {bounds['min_length']} characters")
    return f" ({', '.join(parts)})" if parts else ""


def _default_text(field: FieldInfo) -> str:
    default = field.default
    if default is None:
        return "unset"
    if isinstance(default, str) and default.startswith(PLACEHOLDER_PREFIXES):
        return "development placeholder, refused in production"
    if isinstance(default, bool):
        return f"`{str(default).lower()}`"
    if isinstance(default, time):
        return f"`{default.strftime('%H:%M')}`"
    if isinstance(default, int):
        return f"`{default:,}`" if abs(default) >= 10_000 else f"`{default}`"
    if default == "":
        return "empty"
    return f"`{default}`"


def _is_secret(field: FieldInfo) -> bool:
    return _is_secret_str(field.annotation) or field.repr is False


def _cell(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


def _row(prefix: str, name: str, field: FieldInfo) -> str:
    if not field.description:
        raise ValueError(f"Settings.{name} has no Field(description=...)")
    return (
        f"| `{prefix}{name.upper()}` | {_cell(_type_text(field.annotation) + _limits(field))} "
        f"| {_cell(_default_text(field))} | {'yes' if _is_secret(field) else 'no'} "
        f"| {_cell(field.description)} |"
    )


def render() -> str:
    prefix = str(Settings.model_config.get("env_prefix") or "")
    fields = Settings.model_fields
    unplaced = [name for name in fields if not any(group.matches(name) for group in GROUPS)]
    if unplaced:
        raise ValueError(f"settings in no group of the configuration reference: {unplaced}")
    lines = [
        "# Configuration reference",
        "",
        f"{GENERATED_MARKER} from `sidekick.shared.config.Settings`. Do not edit by hand. -->",
        "",
        f"Sidekick reads {len(fields)} environment variables, all prefixed `{prefix}`. Set them in "
        "the process environment or in a `.env` file in the directory the backend is started "
        "from. The executable truth is the `Settings` class in "
        "[backend/src/sidekick/shared/config/](../../backend/src/sidekick/shared/config/); "
        "this page is rendered from it and a test fails when the two differ.",
        "",
        f"- An unknown `{prefix}*` variable stops startup, so a misspelled name cannot leave a "
        "setting on its default.",
        "- **Secret** `yes` means the value is kept out of `repr` and logs; it is never printed "
        "here.",
        "- Examples: [.env.example](../../.env.example) for local development, "
        "[selfhost.env.example](../../deploy/selfhost/selfhost.env.example) for a self-hosted "
        "instance.",
        "",
    ]
    for group in GROUPS:
        lines += [
            f"## {group.title}",
            "",
            group.summary,
            "",
            "| Variable | Type | Default | Secret | Description |",
            "| --- | --- | --- | --- | --- |",
        ]
        lines += [
            _row(prefix, name, field) for name, field in fields.items() if group.matches(name)
        ]
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def stale_problems(rendered: str, path: Path) -> list[str]:
    """What differs between the rendered page and the file; empty when it is up to date."""
    if not path.is_file():
        return [f"missing: {path}"]
    if path.read_text(encoding="utf-8") != rendered:
        return [f"out of date: {path}"]
    return []


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument(
        "--check",
        action="store_true",
        help="write nothing; exit 1 when --output differs from what Settings renders",
    )
    args = parser.parse_args()
    rendered = render()
    if not args.check:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(rendered, encoding="utf-8")
        return 0
    problems = stale_problems(rendered, args.output)
    for problem in problems:
        print(problem, file=sys.stderr)
    if problems:
        print(
            "regenerate with: "
            "uv run --project backend python -m sidekick.shared.export_settings_reference",
            file=sys.stderr,
        )
    return 1 if problems else 0


if __name__ == "__main__":
    raise SystemExit(main())
