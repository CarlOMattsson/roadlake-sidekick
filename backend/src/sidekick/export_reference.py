def _escape(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


def _header(title: str) -> list[str]:
    return [f"# {title}", "", f"{GENERATED_MARKER}. Do not edit by hand. -->", ""]


def _sentence(text: str) -> str:
    """Help texts start in lower case; a table cell reads better as a sentence."""
    text = _escape(text)
    return text[:1].upper() + text[1:] + ("" if text.endswith(".") or not text else ".")


# --- CLI reference ------------------------------------------------------------------------------


def _subparsers(parser: argparse.ArgumentParser) -> Any | None:
    """The subparsers action of a parser (it holds `choices` and `_choices_actions`), if any."""
    for action in parser_actions(parser):
        if is_subparsers_action(action):
            return cast("Any", action)
    return None


def _exclusive_peers(parser: argparse.ArgumentParser) -> dict[str, list[str]]:
    """For each option in a mutually exclusive group, the other options of the group."""
    peers: dict[str, list[str]] = {}
    for group in parser_exclusive_groups(parser):
        names = [_names(action) for action in group]
        for name in names:
            peers[name] = [other for other in names if other != name]
    return peers


def _names(action: argparse.Action) -> str:
    if action.option_strings:
        return ", ".join(f"`{option}`" for option in action.option_strings)
    return f"`{action.metavar or action.dest}`"


def _value(action: argparse.Action) -> str:
    """The value an option takes, or `-` for a flag."""
    if action.nargs == 0:
        return "-"
    if action.metavar and not isinstance(action.metavar, tuple):
        return f"`{action.metavar}`"
    if action.option_strings:
        return f"`{action.dest.upper()}`"
    return "-"


def _argument_notes(action: argparse.Action, peers: list[str]) -> str:
    notes: list[str] = []
    if action.help:
        notes.append(_sentence(action.help))
    if action.choices is not None and not action.metavar:
        notes.append("One of " + ", ".join(f"`{choice}`" for choice in action.choices) + ".")
    if is_append_action(action):
        notes.append("Repeatable.")
    default = action.default
    if default not in (None, False, argparse.SUPPRESS) and "default" not in (action.help or ""):
        notes.append(f"Default `{default}`.")
    if peers:
        notes.append(f"Cannot be combined with {', '.join(peers)}.")
    return " ".join(notes) or "-"


def _argument_table(parser: argparse.ArgumentParser) -> list[str]:
    peers = _exclusive_peers(parser)
    rows: list[str] = []
    for action in parser_actions(parser):
        if is_help_action(action) or is_subparsers_action(action):
            continue
        required = "yes" if action.required or not action.option_strings else "no"
        if not action.option_strings and action.nargs == "?":
            required = "no"
        rows.append(
            f"| {_names(action)} | {_escape(_value(action))} | {required} | "
            f"{_argument_notes(action, peers.get(_names(action), []))} |"
        )
    if not rows:
        return ["No arguments.", ""]
    return ["| Argument | Value | Required | Notes |", "| --- | --- | --- | --- |", *rows, ""]


def _command_sections(spec: CliSpec, parser: argparse.ArgumentParser) -> list[str]:
    usage = "<command> [arguments]" if _subparsers(parser) else "[arguments]"
    lines = [
        f"## `{spec.command}`",
        "",
        spec.summary,
        "",
        "Run it with:",
        "",
        "```",
        f"{spec.run} {usage}",
        "```",
        "",
    ]
    if sub := _subparsers(parser):
        helps = {choice.dest: choice.help or "" for choice in subparser_choice_actions(sub)}
        lines += ["| Command | What it does |", "| --- | --- |"]
        lines += [
            f"| [`{name}`](#{_anchor(spec, name)}) | {_sentence(helps[name])} |"
            for name in sub.choices
        ]
        lines.append("")
        for name, child in sub.choices.items():
            lines += [f"### `{spec.command} {name}`", "", _sentence(helps[name]), ""]
            lines += _argument_table(child)
    else:
        lines += _argument_table(parser)
    return lines


def _anchor(spec: CliSpec, name: str) -> str:
    return f"{spec.command} {name}".replace(" ", "-")


def _load_parser(spec: CliSpec) -> argparse.ArgumentParser:
    factory = cast(
        "Callable[[], argparse.ArgumentParser]",
        getattr(importlib.import_module(spec.module), spec.factory),
    )
    parser = factory()
    parser.prog = spec.command
    return parser


def render_cli() -> str:
    lines = [
        *_header("Command-line reference"),
        "The operator commands of a Sidekick installation. Each reads its settings from the "
        "environment (and `.env`), like the API; the operator's access to the host is the "
        "authorization. The text of every command and argument is the `help=` in its parser, so "
        "this page cannot drift from `--help`.",
        "",
        "| Command | What it does |",
        "| --- | --- |",
        *[f"| [`{spec.command}`](#{spec.command}) | {spec.summary} |" for spec in CLIS],
        "",
    ]
    for spec in CLIS:
        lines += _command_sections(spec, _load_parser(spec))
    return "\n".join(lines).rstrip("\n") + "\n"


# --- Scope reference ----------------------------------------------------------------------------


def _code_list(items: list[str]) -> str:
    return ", ".join(f"`{item}`" for item in items) or "-"


def _room_of(scope: str) -> str:
    return next((room for room, scopes in ROOM_SCOPES.items() if scope in scopes), "-")


def _mcp_tools(scope: str) -> str:
    needed = sorted(
        name
        for name, scopes in TOOL_SCOPES.items()
        if scope in scopes.requires or scope in scopes.any_of
    )
    optional = sorted(
        name
        for name, scopes in TOOL_SCOPES.items()
        if scope in scopes.optional and name not in needed
    )
    parts: list[str] = []
    if needed:
        parts.append(f"{len(needed)} tools: {_code_list(needed)}")
    if optional:
        parts.append(f"also used by {_code_list(optional)}")
    return "; ".join(parts) or "none"


def _mcp_scope_rows() -> list[str]:
    rows: list[str] = []
    for scope in MCP_SCOPES:
        opt_in = scope in OPT_IN_SCOPES
        default = "off: opt-in, name it explicitly" if opt_in else "ordinary: granted when named"
        description = _escape(MCP_SCOPE_DESCRIPTIONS[scope])
        rows.append(
            f"| `{scope}` | {description} | {_room_of(scope)} | {default} | {_mcp_tools(scope)} |"
        )
    return rows


def _companion_routes(scope: str) -> str:
    own = [operation.name for operation in OPERATIONS if operation.capability == scope]
    also = [operation.name for operation in OPERATIONS if operation.also == scope]
    parts = [_code_list(own)] if own else []
    if also:
        parts.append(f"also needed by {_code_list(also)}")
    return "; ".join(parts) or "none"


def _companion_rows() -> list[str]:
    presets = {name: scopes for name, scopes in PRESETS.items()}
    rows: list[str] = []
    for scope in sorted(COMPANION_SCOPES):
        preset = [f"`{name}`" for name, scopes in presets.items() if scope in scopes]
        default = "off until named" + (f"; in preset {', '.join(preset)}" if preset else "")
        description = _escape(SCOPE_DESCRIPTIONS[scope]["en"])
        rows.append(f"| `{scope}` | {description} | {_companion_routes(scope)} | {default} |")
    return rows


def render_scopes() -> str:
    lines = [
        *_header("Scope reference"),
        "## MCP scopes",
        "",
        f"The {len(MCP_SCOPES)} scopes the public MCP surface can ever carry (`MCP_SCOPES`). A "
        "personal token holds the subset the operator names with `sidekick-admin create-token "
        "--scope`, an OAuth session the subset in `SIDEKICK_MCP_OAUTH_SCOPES`, and the stdio "
        "server every scope of the rooms that are switched on. No credential can hold more. The "
        "*Tools* column lists the tools that are refused without the scope (some need one of "
        "several scopes, such as `search`) and the tools it only widens; what each tool needs in "
        "full is in the [MCP tool reference](mcp/index.md).",
        "",
        "- **Room**: the scopes of a room that `SIDEKICK_ENABLED_ROOMS` switches off are taken "
        "off the session, so the tools that look across rooms leave that room out.",
        "- **Default**: no scope is implied. *Ordinary* scopes are granted when the token or "
        "policy names them; *opt-in* scopes (`OPT_IN_SCOPES`) are never part of an ordinary "
        "grant and must be named one by one.",
        "",
        "| Scope | What it gives | Room | Default | Tools |",
        "| --- | --- | --- | --- | --- |",
        *_mcp_scope_rows(),
        "",
        "## Companion capabilities",
        "",
        "Device capabilities of a paired companion app (ADR-005). They are not application "
        "scopes: no session, token or MCP credential can hold them, and a companion credential "
        "holds nothing else. Each one maps to a fixed set of operations "
        "(`sidekick.companion.operations`) that the companion routes call. Name them with "
        "`sidekick-companion pair|grant --scope` or a preset.",
        "",
        "| Capability | What it gives | Operations | Default |",
        "| --- | --- | --- | --- |",
        *_companion_rows(),
    ]
    return "\n".join(lines).rstrip("\n") + "\n"


# --- Files --------------------------------------------------------------------------------------


def render_pages() -> dict[str, str]:
    """Every generated page, keyed by file name."""
    return {CLI_PAGE: render_cli(), SCOPES_PAGE: render_scopes()}


def stale_problems(pages: dict[str, str], directory: Path) -> list[str]:
    """What differs between the rendered pages and the directory; empty when it is up to date."""
    problems: list[str] = []
    for name, rendered in sorted(pages.items()):
        path = directory / name
        if not path.is_file():
            problems.append(f"missing: {path}")
        elif path.read_text(encoding="utf-8") != rendered:
            problems.append(f"out of date: {path}")
    return problems


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output-dir", type=Path, default=DEFAULT_OUTPUT_DIR)
    parser.add_argument(
        "--check",
        action="store_true",
        help="write nothing; exit 1 when --output-dir differs from what the code renders",
    )
    args = parser.parse_args()
    pages = render_pages()
    if not args.check:
        args.output_dir.mkdir(parents=True, exist_ok=True)
        for name, rendered in pages.items():
            (args.output_dir / name).write_text(rendered, encoding="utf-8")
        return 0
    problems = stale_problems(pages, args.output_dir)
    for problem in problems:
        print(problem, file=sys.stderr)
    if problems:
        print(
            "regenerate with: uv run --project backend python -m sidekick.export_reference",
            file=sys.stderr,
        )
    return 1 if problems else 0


if __name__ == "__main__":
    raise SystemExit(main())
