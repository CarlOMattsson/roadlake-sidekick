"""Render the operator references `docs/reference/cli.md` and `docs/reference/scopes.md`.

`cli.md` is built from the argparse parsers of the operator commands, so a new command or argument
cannot ship without its `help=` text showing up (and a missing text shows up as a gap). `scopes.md`
is built from the scope tables the server enforces: `MCP_SCOPES` and `OPT_IN_SCOPES` with the tools
from `sidekick.mcp.tool_scopes`, and the companion capabilities with the operations from
`sidekick.companion.operations`. The one hand-written part is the plain-language description of
each MCP scope below; a test requires it to name exactly the scopes in `MCP_SCOPES`.

Building a parser reads no settings and touches no database, so rendering needs neither.

Regenerate or verify with:
    uv run --project backend python -m sidekick.export_reference
    uv run --project backend python -m sidekick.export_reference --check
"""

