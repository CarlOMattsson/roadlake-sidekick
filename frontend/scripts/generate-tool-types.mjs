// Generates frontend/src/lib/mcp/tool-results.generated.ts (types) and tool-shapes.generated.ts (runtime
// shapes, see tool-shapes.mjs) from contracts/mcp-tools.generated.json.
//
//   node scripts/generate-tool-types.mjs          (from frontend/) writes the file
//   node scripts/generate-tool-types.mjs --check  exits 1 when the committed file is stale
//
// The contract lists every MCP tool with an inputSchema and an outputSchema (JSON Schema). This
// script translates both into TypeScript: `ToolInputs[name]` is what a call sends and
// `ToolResults[name]` is the structuredContent a call returns. The apps' transport types
// (src/features/*/transport.ts) are derived from them, and src/lib/mcp/contract-checks.ts proves at
// compile time what derivation cannot: that other tools' results fit the same types.
//
// Decisions:
//  - All tools are generated, not only the ones the frontend calls today. The set is small enough
//    (a few thousand lines after sharing), it needs no grep step that could itself drift, and a new
//    call site can use its type immediately.
//  - Inputs: a property is optional when the schema does not list it in `required` (a `default`
//    means "may be omitted"). Outputs: the backend returns the full model dump, so every property is
//    present in structuredContent even when the schema leaves it out of `required` (fields with a
//    default or default_factory). The tools in SPARSE_OUTPUT_TOOLS drop empty keys (exclude_none /
//    exclude_unset in backend/src/sidekick/mcp), so their outputs keep strict optionality. Add a tool
//    there when the backend starts omitting keys.
//  - A nullable value (anyOf with {"type":"null"}) becomes `T | null`; null and absent stay distinct.
//  - Objects that carry the same `title` and the same schema in two or more places become one named
//    exported alias; everything else is inlined. Output is formatted with the project's prettier so
//    the committed file is prettier-clean and the comparison in the test is byte for byte.
//  - Supported JSON Schema: type (also as a list), properties/required, additionalProperties,
//    items, enum, const, anyOf/oneOf/allOf, nullable, $ref into #/$defs or #/definitions.
import { readFile, writeFile } from "node:fs/promises";
import { dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import prettier from "prettier";
import { generateToolShapes } from "./tool-shapes.mjs";

// Paths come from the module's own file path (a string), not from `new URL`: the unit test runs this
// module under jsdom, whose URL class `fileURLToPath` rejects.
const frontendDir = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const CONTRACT_PATH = resolve(
  frontendDir,
  "../contracts/mcp-tools.generated.json",
);
export const OUTPUT_PATH = resolve(
  frontendDir,
  "src/lib/mcp/tool-results.generated.ts",
);
export const SHAPES_OUTPUT_PATH = resolve(
  frontendDir,
  "src/lib/mcp/tool-shapes.generated.ts",
);
export const REGENERATE_COMMAND =
  "cd frontend && node scripts/generate-tool-types.mjs";

const HEADER = `// GENERATED by scripts/generate-tool-types.mjs from contracts/mcp-tools.generated.json.
// Generated, do not edit. Regenerate with: ${REGENERATE_COMMAND}
/* eslint-disable max-lines, @typescript-eslint/no-redundant-type-constituents */
`;

/** Tools whose structuredContent leaves out unset or null keys (see the header comment). */
export const SPARSE_OUTPUT_TOOLS = new Set([
  "get_today_brief",
  "search",
  "set_license_key",
]);

const IDENTIFIER = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

/** A property key as TypeScript source: bare when it is an identifier, quoted otherwise. */
function propertyKey(name) {
  return IDENTIFIER.test(name) ? name : JSON.stringify(name);
}

/** A stable JSON text of a schema (keys sorted), used to compare schemas for equality. */
function canonical(value) {
  if (Array.isArray(value)) return `[${value.map(canonical).join(",")}]`;
  if (value && typeof value === "object") {
    return `{${Object.keys(value)
      .sort()
      .map((key) => `${JSON.stringify(key)}:${canonical(value[key])}`)
      .join(",")}}`;
  }
  return JSON.stringify(value);
}

/** The PascalCase identifier of a schema title, or null when nothing usable remains. */
function aliasName(title) {
  const words = String(title).match(/[A-Za-z0-9]+/g) ?? [];
  const name = words
    .map((word) => word[0].toUpperCase() + word.slice(1))
    .join("");
  return name && !/^[0-9]/.test(name) ? name : null;
}

/** Whether a schema is an object with named properties, the only kind that gets a shared alias. */
function isNamedObject(schema) {
  return (
    schema &&
    typeof schema === "object" &&
    typeof schema.title === "string" &&
    schema.properties &&
    typeof schema.properties === "object"
  );
}

/** Visits every schema node below `schema` (properties, items, unions, $defs). */
function walkSchemas(schema, visit) {
  if (!schema || typeof schema !== "object") return;
  visit(schema);
  for (const child of Object.values(schema.properties ?? {}))
    walkSchemas(child, visit);
  for (const key of ["items", "additionalProperties"]) {
    if (schema[key] && typeof schema[key] === "object")
      walkSchemas(schema[key], visit);
  }
  for (const key of ["anyOf", "oneOf", "allOf"]) {
    for (const child of schema[key] ?? []) walkSchemas(child, visit);
  }
  for (const key of ["$defs", "definitions"]) {
    for (const child of Object.values(schema[key] ?? {}))
      walkSchemas(child, visit);
  }
}

/** The identity of a shareable schema: its content plus how it is read (input or serialized output). */
function shareKey(node, serialized) {
  return `${serialized ? "out" : "in"}:${canonical(node)}`;
}

/**
 * Finds the object schemas worth sharing: same title and same content in two or more places.
 * Returns a map from canonical text to alias name; a second distinct schema with a taken name
 * gets a numeric suffix, in first-seen order, so the names are stable.
 */
function collectShared(roots) {
  const counts = new Map();
  for (const { schema, serialized } of roots) {
    walkSchemas(schema, (node) => {
      if (!isNamedObject(node)) return;
      const key = shareKey(node, serialized);
      const entry = counts.get(key) ?? { count: 0, title: node.title };
      entry.count += 1;
      counts.set(key, entry);
    });
  }
  const shared = new Map();
  const taken = new Set();
  for (const [key, entry] of counts) {
    if (entry.count < 2) continue;
    const base = aliasName(entry.title);
    if (!base) continue;
    let name = base;
    for (let n = 2; taken.has(name); n += 1) name = `${base}${n}`;
    taken.add(name);
    shared.set(key, name);
  }
  return shared;
}

/**
 * Translates one JSON Schema node to TypeScript source.
 * @param {unknown} schema the node
 * @param {{ root: unknown, shared: Map<string, string>, serialized?: boolean, asAlias?: boolean }} context
 *   `root` resolves $ref; `shared` maps a share key to an alias name; `serialized` marks an output
 *   schema whose properties are all present; `asAlias` is set while emitting the
 *   body of an alias, so the node itself is not replaced by its own name.
 */
export function schemaToType(schema, context) {
  if (schema === true || schema === undefined) return "unknown";
  if (schema === false) return "never";
  if (typeof schema !== "object" || schema === null) return "unknown";

  if (typeof schema.$ref === "string")
    return schemaToType(resolveRef(schema.$ref, context.root), context);

  if (!context.asAlias && isNamedObject(schema)) {
    const name = context.shared.get(shareKey(schema, context.serialized));
    if (name) return name;
  }
  const inner = { ...context, asAlias: false };

  if ("const" in schema) return JSON.stringify(schema.const);
  if (Array.isArray(schema.enum)) {
    return schema.enum.length
      ? schema.enum.map((value) => JSON.stringify(value)).join(" | ")
      : "never";
  }
  for (const key of ["anyOf", "oneOf"]) {
    if (Array.isArray(schema[key])) {
      return unionOf(schema[key].map((member) => schemaToType(member, inner)));
    }
  }
  if (Array.isArray(schema.allOf)) {
    return schema.allOf
      .map((member) => `(${schemaToType(member, inner)})`)
      .join(" & ");
  }

  const nullable = schema.nullable === true ? ["null"] : [];
  const types = Array.isArray(schema.type)
    ? schema.type
    : schema.type
      ? [schema.type]
      : [];
  if (types.length === 0) {
    if (schema.properties)
      return unionOf([objectToType(schema, inner), ...nullable]);
    return unionOf(["unknown", ...nullable]);
  }
  return unionOf([
    ...types.map((type) => typeToType(type, schema, inner)),
    ...nullable,
  ]);
}

/** Joins union members, dropping duplicates and keeping the first-seen order. */
function unionOf(members) {
  const unique = [...new Set(members)];
  return unique.length ? unique.join(" | ") : "never";
}

function typeToType(type, schema, context) {
  switch (type) {
    case "string":
      return "string";
    case "number":
    case "integer":
      return "number";
    case "boolean":
      return "boolean";
    case "null":
      return "null";
    case "array":
      return arrayToType(schema, context);
    case "object":
      return objectToType(schema, context);
    default:
      throw new Error(`Unsupported JSON Schema type: ${String(type)}`);
  }
}

function arrayToType(schema, context) {
  if (Array.isArray(schema.prefixItems)) {
    return `[${schema.prefixItems.map((member) => schemaToType(member, context)).join(", ")}]`;
  }
  return `Array<${schemaToType(schema.items, context)}>`;
}

function objectToType(schema, context) {
  const properties = schema.properties ?? {};
  const required = new Set(schema.required ?? []);
  const lines = Object.entries(properties).map(([name, child]) => {
    const present = required.has(name) || context.serialized;
    const optional = present ? "" : "?";
    return `${propertyKey(name)}${optional}: ${schemaToType(child, context)};`;
  });
  const extra = schema.additionalProperties;
  if (extra && typeof extra === "object") {
    lines.push(`[key: string]: ${schemaToType(extra, context)};`);
  }
  if (lines.length === 0) return "Record<string, unknown>";
  return `{\n${lines.join("\n")}\n}`;
}

function resolveRef(ref, root) {
  const match = /^#\/(\$defs|definitions)\/(.+)$/.exec(ref);
  const target = match
    ? root?.[match[1]]?.[decodeURIComponent(match[2])]
    : undefined;
  if (target === undefined) throw new Error(`Unresolvable $ref: ${ref}`);
  return target;
}

/**
 * The TypeScript source (unformatted) for a list of MCP tools.
 * @param {Array<{ name: string, inputSchema: unknown, outputSchema?: unknown }>} tools
 */
function buildSource(tools) {
  const sorted = [...tools].sort((a, b) => a.name.localeCompare(b.name));
  const roots = sorted
    .flatMap((tool) => [
      { schema: tool.inputSchema, serialized: false },
      {
        schema: tool.outputSchema,
        serialized: !SPARSE_OUTPUT_TOOLS.has(tool.name),
      },
    ])
    .filter(({ schema }) => schema);
  const shared = collectShared(roots);

  // Alias bodies are emitted from the first occurrence of each shared schema.
  const aliasBodies = new Map();
  for (const { schema: root, serialized } of roots) {
    walkSchemas(root, (node) => {
      if (!isNamedObject(node)) return;
      const name = shared.get(shareKey(node, serialized));
      if (name && !aliasBodies.has(name)) {
        aliasBodies.set(
          name,
          schemaToType(node, { root, shared, serialized, asAlias: true }),
        );
      }
    });
  }

  const section = (field) =>
    sorted
      .map((tool) => {
        const schema = tool[field];
        const serialized =
          field === "outputSchema" && !SPARSE_OUTPUT_TOOLS.has(tool.name);
        const type = schema
          ? schemaToType(schema, { root: schema, shared, serialized })
          : "unknown";
        return `${propertyKey(tool.name)}: ${type};`;
      })
      .join("\n");

  const aliases = [...aliasBodies.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([name, body]) => `export type ${name} = ${body};`)
    .join("\n\n");

  return [
    HEADER,
    "/** The structuredContent each tool returns, by tool name. */",
    `export type ToolResults = {\n${section("outputSchema")}\n};`,
    "/** The arguments each tool accepts, by tool name. */",
    `export type ToolInputs = {\n${section("inputSchema")}\n};`,
    "/** The name of every tool in the contract. */",
    "export type ToolName = keyof ToolResults;",
    "/** Object shapes that several tools share, named after their schema title. */",
    aliases,
  ].join("\n");
}

/**
 * Generates the formatted TypeScript text for a list of tools (the contract file's content).
 * @param {Array<{ name: string, inputSchema: unknown, outputSchema?: unknown }>} tools
 * @returns {Promise<string>}
 */
export async function generateToolTypes(tools) {
  const config = (await prettier.resolveConfig(OUTPUT_PATH)) ?? {};
  return prettier.format(buildSource(tools), {
    ...config,
    parser: "typescript",
  });
}

/** Reads and parses the contract file. */
export async function readContract(path = CONTRACT_PATH) {
  return JSON.parse(await readFile(path, "utf8"));
}

/**
 * Generates the formatted text of the shape file (the runtime twin of the types, see tool-shapes.mjs).
 * @param {Array<{ name: string, outputSchema?: unknown }>} tools
 * @returns {Promise<string>}
 */
export function generateToolShapeFile(tools) {
  return generateToolShapes(tools, SHAPES_OUTPUT_PATH);
}

async function main() {
  const tools = await readContract();
  const outputs = [
    [OUTPUT_PATH, await generateToolTypes(tools)],
    [SHAPES_OUTPUT_PATH, await generateToolShapeFile(tools)],
  ];
  if (process.argv.includes("--check")) {
    for (const [path, text] of outputs) {
      const current = await readFile(path, "utf8").catch(() => "");
      if (current !== text) {
        console.error(`${path} is stale. Run: ${REGENERATE_COMMAND}`);
        process.exitCode = 1;
      }
    }
    return;
  }
  for (const [path, text] of outputs) {
    await writeFile(path, text);
    console.log(`Wrote ${relative(frontendDir, path)}`);
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) await main();
