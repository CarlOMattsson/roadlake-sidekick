// Generates frontend/src/lib/mcp/tool-shapes.generated.ts: the runtime twin of tool-results.generated.ts.
//
// tool-results.generated.ts is types only and is erased at build time. The apps also need to check at
// runtime that a tool result has the shape they are about to read (a result may come from an older
// server, or be malformed). This module reduces the outputSchema of the tools listed in SHAPE_TOOLS to
// a small "shape" (see src/lib/mcp/shape.ts for how a shape is matched) and writes one exported
// constant per tool, so a bundle carries only the shapes it imports.
//
// Reduction decisions:
//  - Kept: type (a list becomes anyOf; integer becomes number), properties, required, items,
//    additionalProperties (when it is a schema), anyOf/oneOf, const, nullable.
//  - enum is reduced to the type of its values, not the list of values: a newer server may add a
//    value, and an older app must still read the record.
//  - Dropped: description, title, default, format and other annotations.
//  - $ref, allOf and prefixItems are not used by these schemas today. The reducer throws on them,
//    so the shape can never silently become weaker than the schema.
import prettier from "prettier";

/**
 * The tools whose result shape a frontend guard needs. Add a tool here when a new guard reads its
 * result; the generated file grows by that tool's shape only.
 */
export const SHAPE_TOOLS = [
  "create_contact",
  "get_contact_context",
  "get_project",
  "get_task",
  "get_work_agenda",
  "get_work_hierarchy",
  "list_contacts",
];

const SCALAR_TYPES = new Set([
  "string",
  "number",
  "integer",
  "boolean",
  "null",
]);

const HEADER = `// GENERATED by scripts/generate-tool-types.mjs (scripts/tool-shapes.mjs) from contracts/mcp-tools.generated.json.
// Generated, do not edit. Regenerate with: cd frontend && node scripts/generate-tool-types.mjs
import type { Shape } from "./shape";
`;

/** The shape constant name of a tool: get_task becomes getTaskResultShape. */
export function shapeConstantName(toolName) {
  const camel = toolName.replace(/_([a-z0-9])/g, (_, ch) => ch.toUpperCase());
  return `${camel}ResultShape`;
}

/** A JSON type name as the shape knows it (integer is a number). */
function scalarType(type) {
  if (!SCALAR_TYPES.has(type))
    throw new Error(`Unsupported JSON Schema type: ${String(type)}`);
  return type === "integer" ? "number" : type;
}

/** The JSON type a literal value has, as a shape type. */
function typeOfValue(value) {
  if (value === null) return "null";
  if (Array.isArray(value)) return "array";
  return scalarType(typeof value === "number" ? "number" : typeof value);
}

/** Joins alternatives into one shape: a single member stands alone, none means "anything". */
function anyOf(members) {
  const unique = [];
  const seen = new Set();
  for (const member of members) {
    const key = JSON.stringify(member);
    if (!seen.has(key)) {
      seen.add(key);
      unique.push(member);
    }
  }
  if (unique.length === 0) return {};
  return unique.length === 1 ? unique[0] : { anyOf: unique };
}

/**
 * Reduces one JSON Schema node to a shape.
 * @param {unknown} schema the node
 * @returns {object} the shape
 */
export function schemaToShape(schema) {
  if (schema === true || schema === undefined || schema === null) return {};
  if (typeof schema !== "object") throw new Error("Unsupported schema node");
  for (const key of ["$ref", "allOf", "prefixItems"]) {
    if (key in schema)
      throw new Error(
        `Unsupported JSON Schema keyword in a shape tool: ${key}`,
      );
  }
  if ("const" in schema) return { const: schema.const };
  if (Array.isArray(schema.enum))
    return anyOf(schema.enum.map((value) => ({ type: typeOfValue(value) })));
  for (const key of ["anyOf", "oneOf"]) {
    if (Array.isArray(schema[key]))
      return anyOf(schema[key].map(schemaToShape));
  }
  const types = Array.isArray(schema.type)
    ? schema.type
    : schema.type
      ? [schema.type]
      : [];
  const members = types.map((type) => typedShape(type, schema));
  if (schema.nullable === true) members.push({ type: "null" });
  if (types.length === 0 && schema.properties)
    members.unshift(objectShape(schema));
  return anyOf(members);
}

function typedShape(type, schema) {
  if (type === "array")
    return { type: "array", items: schemaToShape(schema.items) };
  if (type === "object") return objectShape(schema);
  return { type: scalarType(type) };
}

function objectShape(schema) {
  const shape = { type: "object" };
  if (schema.properties) {
    shape.properties = Object.fromEntries(
      Object.entries(schema.properties).map(([name, child]) => [
        name,
        schemaToShape(child),
      ]),
    );
    shape.required = [...(schema.required ?? [])];
  }
  if (
    schema.additionalProperties &&
    typeof schema.additionalProperties === "object"
  )
    shape.additionalProperties = schemaToShape(schema.additionalProperties);
  return shape;
}

/**
 * The formatted TypeScript text of the shape file for a list of contract tools.
 * @param {Array<{ name: string, outputSchema?: unknown }>} tools
 * @param {string} prettierConfigPath a path inside the project, to resolve its prettier config
 */
export async function generateToolShapes(tools, prettierConfigPath) {
  const byName = new Map(tools.map((tool) => [tool.name, tool]));
  const blocks = SHAPE_TOOLS.map((name) => {
    const tool = byName.get(name);
    if (!tool?.outputSchema)
      throw new Error(`Shape tool ${name} has no outputSchema in the contract`);
    const shape = JSON.stringify(schemaToShape(tool.outputSchema));
    return `/** The shape of the structuredContent ${name} returns. */\nexport const ${shapeConstantName(name)}: Shape = ${shape};`;
  });
  const config = (await prettier.resolveConfig(prettierConfigPath)) ?? {};
  return prettier.format([HEADER, ...blocks].join("\n"), {
    ...config,
    parser: "typescript",
  });
}
