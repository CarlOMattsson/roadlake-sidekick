describe("schemaToType", () => {
  const schema = {
    type: "object",
    required: ["id"],
    properties: {
      id: { type: "string", format: "uuid" },
      note: { anyOf: [{ type: "string" }, { type: "null" }], default: null },
      count: { type: "integer", default: 0 },
      status: { enum: ["todo", "done"], type: "string" },
      tags: { type: "array", items: { type: "string" } },
    },
  };

  it("makes unlisted properties optional and nullable unions explicit", () => {
    const text = typeOf(schema);
    expect(text).toContain("id: string;");
    expect(text).toContain("note?: string | null;");
    expect(text).toContain("count?: number;");
    expect(text).toContain('status?: "todo" | "done";');
    expect(text).toContain("tags?: Array<string>;");
  });

  it("treats every output property as present in serialized mode", () => {
    const text = typeOf(schema, true);
    expect(text).toContain("note: string | null;");
    expect(text).toContain("count: number;");
    expect(text).not.toContain("?:");
  });

  it("resolves $ref into $defs and quotes keys that are not identifiers", () => {
    const withRef = {
      type: "object",
      required: ["a-b"],
      properties: { "a-b": { $ref: "#/$defs/Name" } },
      $defs: { Name: { type: "string" } },
    };
    expect(typeOf(withRef)).toContain('"a-b": string;');
    expect(() => typeOf({ $ref: "#/$defs/Missing" })).toThrow(/Unresolvable/);
  });

  it("maps dictionaries, tuples, const, type lists and nullable", () => {
    expect(
      typeOf({ type: "object", additionalProperties: { type: "integer" } }),
    ).toContain("[key: string]: number;");
    expect(typeOf({ type: "object" })).toBe("Record<string, unknown>");
    expect(
      typeOf({
        type: "array",
        prefixItems: [{ type: "string" }, { type: "null" }],
      }),
    ).toBe("[string, null]");
    expect(typeOf({ const: "x" })).toBe('"x"');
    expect(typeOf({ type: ["string", "null"] })).toBe("string | null");
    expect(typeOf({ type: "string", nullable: true })).toBe("string | null");
    expect(typeOf({ oneOf: [{ type: "boolean" }, { type: "number" }] })).toBe(
      "boolean | number",
    );
  });

  it("rejects a schema type it cannot express", () => {
    expect(() => typeOf({ type: "bigint" })).toThrow(/Unsupported/);
  });
});
