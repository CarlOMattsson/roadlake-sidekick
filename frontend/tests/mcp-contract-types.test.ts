import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import {
  CONTRACT_PATH,
  OUTPUT_PATH,
  SHAPES_OUTPUT_PATH,
  REGENERATE_COMMAND,
  generateToolShapeFile,
  generateToolTypes,
  readContract,
  schemaToType,
} from "../scripts/generate-tool-types.mjs";

/** Translates a schema with no sharing, the way a single output property is read. */
function typeOf(schema: unknown, serialized = false): string {
  return schemaToType(schema, {
    root: schema,
    shared: new Map<string, string>(),
    serialized,
  });
}

describe("generated MCP tool types", () => {
  it("match the committed file byte for byte", async () => {
    const generated = await generateToolTypes(await readContract());
    const committed = readFileSync(OUTPUT_PATH, "utf8");
    // A plain boolean keeps a failure from dumping two 2000-line files; the message names the fix.
    const upToDate = generated === committed;
    expect(
      upToDate,
      `src/lib/mcp/tool-results.generated.ts is stale against contracts/mcp-tools.generated.json. Regenerate it with: ${REGENERATE_COMMAND}`,
    ).toBe(true);
  });

  it("differ once a contract field changes", async () => {
    const tools = await readContract();
    const changed = structuredClone(tools);
    const task = changed.find((tool) => tool.name === "get_task");
    const taskSchema = (task?.outputSchema as { properties: object })
      .properties;
    delete (taskSchema as Record<string, unknown>).task;
    const generated = await generateToolTypes(changed);
    expect(generated).not.toBe(readFileSync(OUTPUT_PATH, "utf8"));
  });

  it("name every tool of the contract in both maps", async () => {
    const tools = await readContract();
    const committed = readFileSync(OUTPUT_PATH, "utf8");
    expect(tools.length).toBeGreaterThan(0);
    for (const tool of tools) {
      expect(committed).toContain(`  ${tool.name}: `);
    }
    expect(CONTRACT_PATH).toContain("mcp-tools.generated.json");
  });

  it("carry the do-not-edit header and the regenerate command", () => {
    const committed = readFileSync(OUTPUT_PATH, "utf8");
    expect(committed.startsWith("// GENERATED by")).toBe(true);
    expect(committed).toContain("do not edit");
    expect(committed).toContain(REGENERATE_COMMAND);
  });
});

